import { Palette } from "./palette";

export interface ColorSchemePairings {
  /** Id preset tipografi dari motion/text-styles.ts (rekomendasi). */
  textStyle?: string;
  /** Id gaya CC dari captions/cc-styles.ts (rekomendasi). */
  ccStyle?: string;
  /** Id backdrop dari motion/backdrops.ts (rekomendasi). */
  backdrop?: string;
}

export interface ColorSchemeDef {
  id: string;
  name: string;
  /** Suasana/keluarga skema, untuk log dan katalog. */
  mood: string;
  palette: Palette;
  pairings: ColorSchemePairings;
}

